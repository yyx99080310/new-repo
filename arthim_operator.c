//addition
#include<stdio.h>
int main() {

    int a, b, sum;
    printf("enter two numbers:");
    scanf("%d%d", &a, &b);
    sum = a + b;
    printf("the sum of %d and %d is %d", a, b, sum);
    return 0;

}
